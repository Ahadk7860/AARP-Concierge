#!/usr/bin/env bash
# Pass 1 of the track review. Run from INSIDE the track's worktree, on the Mac.
#
#     bash scripts/review-capture.sh a
#
# Re-runs this track's test, lint and ownership commands and writes everything the
# other two review passes need into review-capture-<letter>.md in this worktree.
#
# Why it lives here rather than in the planning session: the planning session runs in a
# Linux container with no Swift, no Xcode and no local Postgres. It cannot execute
# Track A's suite or Track D's migrations. A review that skips execution is a review of
# prose, so execution happens where it can, and only the output travels.
#
# It does not fix anything and it does not stop on failure -- a failing command IS the
# finding, and hiding it would defeat the point.

set -uo pipefail

LETTER="${1:-}"
BASE="${BOI_BASE:-main}"
if [ -z "$LETTER" ]; then echo "usage: review-capture.sh <a|b|c|d>" >&2; exit 2; fi

case "$LETTER" in
  a) SLUG="mac";           TEST="swift test --package-path mac"
     LINT="swift build --package-path mac -Xswiftc -warnings-as-errors" ;;
  b) SLUG="intelligence";  TEST="python3 -m pytest"
     LINT="ruff check intelligence" ;;
  c) SLUG="transport";     TEST="npm test -- cloud/channel cloud/mock-linq"
     LINT="npm run lint && npm run typecheck" ;;
  d) SLUG="cloud-surface"; TEST="npm test -- cloud/api cloud/brief cloud/card cloud/db"
     LINT="npm run lint && npm run typecheck" ;;
  *) echo "unknown track: $LETTER" >&2; exit 2 ;;
esac

cd "$(git rev-parse --show-toplevel)"

# Per-worktree virtualenvs are the norm, and a bare `python`/`ruff` that resolves to
# nothing is how "EXIT: 0" got reported for a command that never executed.
[ -d .venv/bin ] && PATH="$PWD/.venv/bin:$PATH" && export PATH

require () {
  command -v "$1" >/dev/null 2>&1 && return 0
  echo "MISSING INTERPRETER: $1 is not on PATH." >&2
  echo "A capture that cannot run its own commands is not evidence." >&2
  exit 3
}
case "$LETTER" in
  a) require swift ;;
  b) require python3 ;;
  c|d) require npx ;;
esac

OUT="review-capture-$LETTER.md"
BRANCH="$(git branch --show-current)"

{
  echo "# Track ${LETTER} — Pass 1 evidence capture"
  echo
  echo "Branch: \`$BRANCH\`  ·  Base: \`$BASE\`  ·  Worktree: \`$(pwd)\`"
  echo
  echo "Generated by \`scripts/review-capture.sh\`. Every command below was re-run from"
  echo "this worktree; none of it is the working agent's claim."
  echo

  echo "## Working tree state"
  echo '```'
  git status --short || true
  echo "(empty above means clean)"
  echo '```'
  echo

  echo "## Commits on this branch"
  echo '```'
  git log --oneline "$BASE"..HEAD || true
  echo '```'
  echo
  echo "One commit per prompt is the expectation. Several commits on one prompt is"
  echo "correct and healthy. A single commit for the whole track means the audit trail"
  echo "was laundered."
  echo

  echo "## Files changed"
  echo '```'
  git diff --stat "$BASE"...HEAD || true
  echo '```'
  echo

  echo "## Ownership and frozen-file check"
  echo '```'
  bash scripts/check-ownership.sh "$LETTER" 2>&1 || echo "EXIT: $?"
  echo '```'
  echo

  echo "## Tests"
  echo "\`$TEST\`"
  echo '```'
  eval "$TEST" 2>&1 | tail -120
  rc=${PIPESTATUS[0]}          # capture IMMEDIATELY -- no `|| true` between, ever
  echo "EXIT: $rc"
  [ "$rc" -ne 0 ] && echo ">>> TESTS FAILED <<<"
  echo '```'
  echo

  echo "## Lint"
  echo "\`$LINT\`"
  echo '```'
  eval "$LINT" 2>&1 | tail -60
  rc=${PIPESTATUS[0]}
  echo "EXIT: $rc"
  [ "$rc" -ne 0 ] && echo ">>> LINT FAILED <<<"
  echo '```'
  echo

  echo "## Contract fixtures still valid"
  echo '```'
  python3 scripts/validate_fixtures.py 2>&1 || echo "EXIT: $?"
  echo '```'
  echo

  echo "## NOTES.md"
  echo
  if [ -f "prompts/track-$LETTER-$SLUG/NOTES.md" ]; then
    cat "prompts/track-$LETTER-$SLUG/NOTES.md"
  else
    echo "_missing — that is itself a finding_"
  fi
  echo

  echo "## Prompt status table"
  echo '```'
  sed -n '/^| # | File | Outcome/,/^$/p' "prompts/track-$LETTER-$SLUG/TRACK.md" || true
  echo '```'
} > "$OUT" 2>&1

echo "wrote $OUT"
echo
echo "Next:"
echo "  1. Hand $OUT to the planning session (Pass 3)."
echo "  2. Full diff, if the planning session asks for it:"
echo "       git diff $BASE...HEAD > review-diff-$LETTER.patch"
echo "  3. Do not fix anything found here inside this session. Report it."
